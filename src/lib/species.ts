type Draft = {
  id: string;
  name: string;
  latin: string;
  family: string;
  kind?: Kind;
  layer: Layer;
  edible?: boolean;
  functions: EcoFunction[];
  hz: [number, number];
  soils?: Soil[];
  water?: WaterNeed;
  sun?: SunNeed;
  root?: RootDepth;
  years?: number;
  companions?: string[];
  antagonists?: string[];
  allelopathic?: boolean;
  livestockSafe?: boolean;
  fodderFor?: string[];
  nutrients?: Nutrients;
  description: string;
  agro: string;
  yields: string;
  color: PlantColor;
  silhouette: Silhouette;
};

function s(d: Draft): Species {
  return {
    id: d.id,
    name: d.name,
    latin: d.latin,
    family: d.family,
    kind: d.kind ?? "plant",
    layer: d.layer,
    edible: d.edible ?? true,
    functions: d.functions,
    hardinessMin: d.hz[0],
    hardinessMax: d.hz[1],
    soils: d.soils ?? ["loam", "silt"],
    water: d.water ?? "moderate",
    sun: d.sun ?? "full",
    root: d.root ?? "medium",
    yearsToYield: d.years ?? 3,
    companions: d.companions ?? [],
    antagonists: d.antagonists ?? [],
    allelopathic: d.allelopathic ?? false,
    livestockSafe: d.livestockSafe ?? true,
    fodderFor: d.fodderFor ?? [],
    nutrients: d.nutrients ?? {},
    description: d.description,
    agro: d.agro,
    yields: d.yields,
    color: d.color,
    silhouette: d.silhouette,
  };
}

