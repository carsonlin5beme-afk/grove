for (const sp of SPECIES) {
  sp.functions = sp.functions.filter(Boolean);
  const extra = NUTRIENT_BOOSTS[sp.id];
  if (extra) Object.assign(sp.nutrients, extra);
}

export const SPECIES_BY_ID: Record<string, Species> = Object.fromEntries(
  SPECIES.map((sp) => [sp.id, sp]),
);

export function getSpecies(id: string): Species | undefined {
  return SPECIES_BY_ID[id];
}

export function searchSpecies(query: string): Species[] {
  const q = query.trim().toLowerCase();
  if (!q) return SPECIES;
  return SPECIES.filter((sp) => {
    const hay = [
      sp.name,
      sp.latin,
      sp.family,
      sp.layer,
      sp.kind,
      ...sp.functions,
      sp.description,
      sp.agro,
      sp.yields,
      chemistryHaystack(sp),
    ]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}

export const FAMILIES = [...new Set(SPECIES.map((s) => s.family))].sort();
